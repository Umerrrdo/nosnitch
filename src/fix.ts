import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { NosnitchError } from "./errors.js";
import type { ServiceResult } from "./scanner.js";

export const OVERRIDE_FILE = "compose.nosnitch.override.yml";

/** The override sits next to the first compose file so relative paths keep working. */
export function overridePath(composeFile: string): string {
  return join(dirname(resolve(composeFile)), OVERRIDE_FILE);
}

/**
 * Builds a compose override holding only the environment additions that turn
 * telemetry off. Returns null when there is nothing to add.
 */
export function buildOverride(results: ServiceResult[], composeFileName: string): string | null {
  const fixable = results.filter((r) => r.fix_env.length > 0);
  if (fixable.length === 0) return null;

  const lines = [
    "# Generated by nosnitch. Turns off telemetry that is on by default.",
    `# Use it with: docker compose -f ${composeFileName} -f ${OVERRIDE_FILE} up -d`,
    "services:",
  ];
  for (const r of fixable) {
    if (!r.verified) lines.push(`  # ${r.app}: unverified database entry, check the source before relying on it.`);
    lines.push(`  ${JSON.stringify(r.service)}:`, "    environment:");
    for (const e of r.fix_env) lines.push(`      ${e.name}: ${JSON.stringify(e.value)}`);
  }
  return `${lines.join("\n")}\n`;
}

/** Writes the override file. The original compose file is never opened for writing. */
export function writeOverride(results: ServiceResult[], composeFile: string): string | null {
  const text = buildOverride(results, composeFile.replace(/^.*[\\/]/, ""));
  if (text === null) return null;
  const target = overridePath(composeFile);
  try {
    writeFileSync(target, text);
  } catch (err) {
    throw new NosnitchError(
      `Could not write ${target}: ${(err as Error).message}`,
      "Check that the folder is writable. In Docker, mount the folder without :ro and, on Linux, add --user $(id -u):$(id -g).",
    );
  }
  return target;
}
